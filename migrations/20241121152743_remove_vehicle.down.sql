CREATE TYPE VEHICLETYPE AS ENUM ('Car', 'Empty');

CREATE TABLE VEHICLE (
    ID int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    UUID uuid UNIQUE NOT NULL,
    PUB_UUID uuid UNIQUE NOT NULL DEFAULT gen_random_uuid(),
    NAME text UNIQUE NOT NULL,
    VEHICLE_TYPE vehicletype NOT NULL DEFAULT 'Car'
);

CREATE TABLE IF NOT EXISTS VEHICLE_TARIFF (
    TARIFF_ID int NOT NULL REFERENCES TARIFF (ID) ON DELETE CASCADE,
    VEHICLE_ID int NOT NULL REFERENCES VEHICLE (ID) ON DELETE CASCADE,
    PRIMARY KEY (TARIFF_ID, VEHICLE_ID)
);

ALTER TABLE IF EXISTS TARIFF ADD COLUMN IF NOT EXISTS ALTERNATIVE_OPERATOR_NAME text;

